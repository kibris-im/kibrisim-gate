#!/usr/bin/env python3
"""Turn the Drive master JPEGs into the gate's background set.

  python3 tools/make-art.py "/path/to/Kıbrısım Tasarım Varlıkları (Visual Assets)"

Reads the files listed in tools/art-captions.json (one best version per place), writes
public/art/<name>.webp (1280x720), src/art-manifest.js and the approval-email header
public/email/header.jpg (six districts side by side). Needs: pip install pillow
"""
import json, os, sys
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else None
if not src or not os.path.isdir(src):
    sys.exit(__doc__)
caps = json.load(open(os.path.join(root, 'tools', 'art-captions.json'), encoding='utf-8'))
out_dir = os.path.join(root, 'public', 'art')
os.makedirs(out_dir, exist_ok=True)
manifest, total = [], 0
for c in caps:
    p = os.path.join(src, c['file'] + '.jpg')
    if not os.path.exists(p):
        print('missing, skipped:', c['file']); continue
    im = Image.open(p).convert('RGB')
    if im.width > 1280:
        im = im.resize((1280, round(im.height * 1280 / im.width)), Image.LANCZOS)
    dst = os.path.join(out_dir, c['file'] + '.webp')
    im.save(dst, 'WEBP', quality=72, method=6)
    total += os.path.getsize(dst)
    manifest.append({'d': c['d'], 'f': c['file'], 'e': 'webp', 'tr': c['tr'], 'en': c['en']})
with open(os.path.join(root, 'src', 'art-manifest.js'), 'w', encoding='utf-8') as fh:
    fh.write('// Generated by tools/make-art.py. Do not edit by hand.\nexport const ART = ')
    json.dump(manifest, fh, ensure_ascii=False, indent=1)
    fh.write(';\n')
print(f'{len(manifest)} images, {total/1e6:.1f} MB total, avg {total/max(1,len(manifest))/1e3:.0f} KB')

# Email header: one picture per district, centre-cropped, six tiles of 200x240 = 1200x240.
HEADER = ['girne-antik-liman-v4', 'lefkosa-buyuk-han-v2', 'gazimagusa-lala-mustafa-pasa-v2',
          'iskele-altinkumsal-v2', 'guzelyurt-narenciye-bahceleri-v2', 'lefke-su-kemerleri-v2']
tiles = []
for name in HEADER:
    p = os.path.join(src, name + '.jpg')
    if not os.path.exists(p):
        # fall back to any converted picture of the same district
        d = next((c['d'] for c in caps if c['file'] == name), None)
        alt = next((c['file'] for c in caps if c['d'] == d and os.path.exists(os.path.join(src, c['file'] + '.jpg'))), None)
        if not alt:
            continue
        p = os.path.join(src, alt + '.jpg')
    im = Image.open(p).convert('RGB')
    w = round(im.width * 240 / im.height)
    im = im.resize((w, 240), Image.LANCZOS)
    left = (w - 200) // 2
    tiles.append(im.crop((left, 0, left + 200, 240)))
if tiles:
    strip = Image.new('RGB', (200 * len(tiles), 240), (250, 249, 245))
    for i, t in enumerate(tiles):
        strip.paste(t, (200 * i, 0))
    os.makedirs(os.path.join(root, 'public', 'email'), exist_ok=True)
    hp = os.path.join(root, 'public', 'email', 'header.jpg')
    strip.save(hp, 'JPEG', quality=85)
    print('email header:', len(tiles), 'tiles,', os.path.getsize(hp) // 1000, 'KB')